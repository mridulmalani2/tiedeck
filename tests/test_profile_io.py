def test_a_font_role_permits_only_what_it_states():
    exact = FontRole(exact_pt=[9.0, 10.0])
    assert exact.permits(9.0) and exact.permits(10.0)
    assert not exact.permits(11.0)

    band = FontRole(min_pt=10.0, max_pt=14.0)
    assert band.permits(10.0) and band.permits(12.0) and band.permits(14.0)
    assert not band.permits(9.0) and not band.permits(18.0)


def test_an_unconstrained_role_permits_nothing_rather_than_everything():
    """An empty band is an absence of evidence, and permitting everything would
    silently disable LO-007 for that role."""
    empty = FontRole()
    assert empty.is_empty
    assert not empty.permits(12.0)
    assert empty.describe() == "unconstrained"


def test_exact_sizes_are_normalised_on_construction():
    assert FontRole(exact_pt=[14.0, 10.0, 10.0]).exact_pt == [10.0, 14.0]


def test_a_box_describes_itself_in_the_units_a_designer_uses():
    described = Box(left=852, top=24, width=72, height=24, tolerance_pt=2.0).describe()
    assert "852pt" in described and "72x24pt" in described and "+/-2pt" in described


def test_locks_apply_to_descendants_but_not_to_siblings():
    profile = _profile()
    profile.locks = ["brand.logo"]
    assert profile.is_locked("brand.logo")
    assert profile.is_locked("brand.logo.per_archetype.content")
    assert not profile.is_locked("brand.logotype")
    assert not profile.is_locked("brand")


def test_the_archetype_of_a_slide_can_be_looked_up_both_ways():
    profile = _profile()
    assert profile.archetype_of(2) == "content"
    assert profile.archetype_of(99) is None


def test_a_severity_override_takes_effect():
    profile = _profile()
    assert profile.severity_of("BR-002", "major") == "major"
    profile.rules.severity_overrides["BR-002"] = "blocker"
    assert profile.severity_of("BR-002", "major") == "blocker"
