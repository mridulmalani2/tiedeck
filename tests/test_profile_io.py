"""Emitting and reading profiles.

A profile is a document a user reads, argues with and edits by hand, so the
round trip has to preserve every value *and* every provenance note. A value lost
in serialisation shows up later as a finding on a deck that passed a moment
earlier, which is the worst way to discover a bug of this kind.
"""

from __future__ import annotations

import pytest

from tieout.learn.emit import (
    PROVENANCE_PREFIX,
    QUESTION_PREFIX,
    iter_provenance,
    render,
    write,
)
from tieout.profile.loader import (
    PROFILE_DIR_ENV,
    ProfileError,
    load,
    load_for_client,
    load_raw,
    load_suppressions,
    profile_dir,
    profile_path,
    read_comment_notes,
    suppression_path,
    write_suppressions,
)
from tieout.profile.schema import (
    Box,
    DeferredQuestion,
    FontRole,
    Profile,
    SlideProfile,
    Suppression,
    SuppressionFile,
)


def _profile() -> Profile:
    profile = Profile(
        client="acme",
        generated_at="2026-09-14",
        sources=["reference.pptx (26 slides)"],
        slide=SlideProfile(width_pt=960.0, height_pt=540.0),
        archetypes={"content": [1, 2, 3]},
    )
    profile.brand.palette_hex = ["#000000", "#1F3864"]
    profile.brand.fonts.allowed = ["Gill Sans MT"]
    profile.brand.fonts.roles = {"body": FontRole(min_pt=10.0, max_pt=14.0)}
    profile.set_provenance("brand.palette_hex", "two clusters across 26 slides", "high")
    profile.set_provenance("brand.fonts.allowed", "100% of characters", "high")
    profile.set_provenance("hygiene", "default, not inferred", "medium")
    return profile


# --------------------------------------------------------------------------------------
# Emitting
# --------------------------------------------------------------------------------------


def test_the_header_records_what_it_learned_from():
    text = render(_profile())
    assert text.startswith("# Generated by tieout learn on 2026-09-14 from:")
    assert "reference.pptx (26 slides)" in text


def test_every_note_appears_as_a_comment_beside_its_value():
    text = render(_profile())
    assert f"{PROVENANCE_PREFIX} two clusters across 26 slides" in text
    assert f"{PROVENANCE_PREFIX} 100% of characters" in text


def test_a_medium_confidence_value_says_so_in_its_comment():
    """A value the evidence only half supports should not read with the same
    authority as one derived from twenty-three slides."""
    assert "[confidence medium]" in render(_profile())


def test_a_deferred_question_is_written_above_the_field_it_concerns():
    profile = _profile()
    profile.questions = [
        DeferredQuestion(
            id="q1",
            field_path="brand.palette_hex",
            question="Is #1F3864 really the house navy?",
            options=["yes", "no"],
            default="yes",
        )
    ]
    text = render(profile)
    assert f"{QUESTION_PREFIX} Is #1F3864 really the house navy?" in text
    assert "Options: yes / no" in text
    assert "Defaulted to: yes" in text
    assert "1 of 1 questions" in text or "Answered 0 of 1" in text


def test_the_sections_whose_purpose_is_not_obvious_are_explained():
    text = render(_profile())
    assert "edit if a slide is wrong" in text
    assert "Silence is correct" in text
    assert "protected from re-learning" in text


def test_provenance_is_also_written_as_data_so_findings_can_cite_it():
    """It is written twice on purpose. Recovering it from comments alone
    mis-assigned notes across section boundaries, because YAML attaches a leading
    comment to the preceding sibling key."""
    text = render(_profile())
    assert "provenance:" in text
    assert "generated:" in text, "the duplication must be labelled as generated"


def test_writing_creates_the_directory(tmp_path):
    target = tmp_path / "nested" / "deeper" / "acme.yaml"
    result = write(_profile(), target)
    assert result.path == target
    assert target.exists()


def test_iter_provenance_is_sorted_and_complete():
    entries = list(iter_provenance(_profile()))
    paths = [path for path, _, _ in entries]
    assert paths == sorted(paths)
    assert ("hygiene", "default, not inferred", "medium") in entries


