def test_a_profile_survives_the_round_trip_intact(tmp_path):
    original = _profile()
    path = tmp_path / "acme.yaml"
    write(original, path)
    reloaded = load(path)

    assert reloaded.client == original.client
    assert reloaded.brand.palette_hex == original.brand.palette_hex
    assert reloaded.brand.fonts.roles["body"].describe() == "10pt to 14pt"
    assert reloaded.archetypes == original.archetypes
    assert reloaded.provenance == original.provenance
    assert reloaded.confidence == original.confidence


def test_each_note_stays_attached_to_its_own_value(tmp_path):
    """The bug that made the comments-only design untenable: a note must never
    migrate to a neighbouring section, because a finding citing the wrong
    evidence is worse than one citing none."""
    original = _profile()
    original.set_provenance("layout.grid", "edge clusters with support of 5", "high")
    original.set_provenance("layout.safe_margin_pt", "5th percentile of edges", "high")
    path = tmp_path / "acme.yaml"
    write(original, path)
    reloaded = load(path)

    assert reloaded.provenance_for("layout.grid") == "edge clusters with support of 5"
    assert reloaded.provenance_for("layout.safe_margin_pt") == "5th percentile of edges"


def test_provenance_falls_back_to_an_ancestor():
    profile = _profile()
    profile.set_provenance("brand.logo", "one image on 23 of 26 slides", "high")
    assert (
        profile.provenance_for("brand.logo.per_archetype.content")
        == "one image on 23 of 26 slides"
    )
    assert profile.provenance_for("nothing.here") is None


def test_a_missing_profile_says_where_it_looked(tmp_path):
    with pytest.raises(ProfileError, match="no profile at"):
        load(tmp_path / "absent.yaml")


def test_an_unparseable_profile_is_rejected_loudly(tmp_path):
    path = tmp_path / "broken.yaml"
    path.write_text("client: [unclosed\n", encoding="utf-8")
    with pytest.raises(ProfileError, match="not valid YAML"):
        load(path)


def test_a_profile_that_is_not_a_mapping_is_rejected(tmp_path):
    path = tmp_path / "list.yaml"
    path.write_text("- one\n- two\n", encoding="utf-8")
    with pytest.raises(ProfileError, match="does not contain a profile mapping"):
        load(path)


def test_an_invalid_profile_fails_at_load_rather_than_at_evaluation(tmp_path):
    """Validating late would surface a typo as a mysterious missing check halfway
    through an audit."""
    path = tmp_path / "wrong.yaml"
    path.write_text("client: acme\nslide:\n  width_pt: wide\n", encoding="utf-8")
    with pytest.raises(ProfileError, match="not a valid profile"):
        load(path)


def test_an_unknown_field_is_an_error_not_a_silent_no_op(tmp_path):
    """A misspelled key that loaded quietly would look like a configured rule and
    behave like an absent one."""
    path = tmp_path / "typo.yaml"
    path.write_text(
        "client: acme\nslide:\n  width_pt: 960\n  height_pt: 540\n"
        "brand:\n  pallete_hex: ['#000000']\n",
        encoding="utf-8",
    )
    with pytest.raises(ProfileError):
        load(path)


def test_load_for_client_resolves_the_profile_directory(tmp_path, monkeypatch):
    monkeypatch.setenv(PROFILE_DIR_ENV, str(tmp_path))
    assert profile_dir() == tmp_path
    write(_profile(), profile_path("acme"))
    assert load_for_client("acme").client == "acme"


def test_load_for_client_prefers_an_explicit_path(tmp_path, monkeypatch):
    monkeypatch.setenv(PROFILE_DIR_ENV, str(tmp_path / "ignored"))
    explicit = tmp_path / "elsewhere.yaml"
    write(_profile(), explicit)
    assert load_for_client("acme", explicit).client == "acme"


def test_a_missing_client_profile_explains_how_to_create_one(tmp_path, monkeypatch):
    monkeypatch.setenv(PROFILE_DIR_ENV, str(tmp_path))
    with pytest.raises(ProfileError, match="tieout learn"):
        load_for_client("ghost")


def test_top_level_comment_notes_can_be_read_back(tmp_path):
    """For `profile show` on a file a user has reformatted by hand."""
    path = tmp_path / "acme.yaml"
    write(_profile(), path)
    notes = read_comment_notes(load_raw(path))
    assert notes.get("slide") is None or isinstance(notes.get("slide"), str)
    assert isinstance(notes, dict)


