def test_a_missing_suppression_file_is_not_an_error(tmp_path, monkeypatch):
    monkeypatch.setenv(PROFILE_DIR_ENV, str(tmp_path))
    loaded = load_suppressions("acme")
    assert loaded.suppressions == []
    assert loaded.client == "acme"


def test_suppressions_round_trip_with_their_counts(tmp_path, monkeypatch):
    """The count is what lets section 8.7 notice a miscalibrated rule, so it has
    to survive the file."""
    monkeypatch.setenv(PROFILE_DIR_ENV, str(tmp_path))
    original = SuppressionFile(
        client="acme",
        suppressions=[Suppression(rule_id="BR-002", slide_index=5, count=3)],
    )
    write_suppressions(original, suppression_path("acme"))
    reloaded = load_suppressions("acme")
    assert reloaded.suppressions[0].count == 3
    assert reloaded.repeat_offenders()


def test_the_suppression_file_explains_itself(tmp_path, monkeypatch):
    monkeypatch.setenv(PROFILE_DIR_ENV, str(tmp_path))
    write_suppressions(SuppressionFile(client="acme"), suppression_path("acme"))
    text = suppression_path("acme").read_text()
    assert "miscalibrated" in text
    assert "learn --add" in text


def test_a_slide_scoped_suppression_only_matches_that_slide():
    suppressions = SuppressionFile(
        suppressions=[Suppression(rule_id="BR-002", slide_index=5)]
    )
    assert suppressions.matches("BR-002", 5)
    assert not suppressions.matches("BR-002", 6)
    assert not suppressions.matches("BR-003", 5)


def test_a_rule_scoped_suppression_matches_every_slide():
    suppressions = SuppressionFile(suppressions=[Suppression(rule_id="LO-004")])
    assert suppressions.matches("LO-004", 1)
    assert suppressions.matches("LO-004", 99)


def test_a_malformed_suppression_file_is_rejected(tmp_path, monkeypatch):
    monkeypatch.setenv(PROFILE_DIR_ENV, str(tmp_path))
    suppression_path("acme").parent.mkdir(parents=True, exist_ok=True)
    suppression_path("acme").write_text("suppressions: not-a-list\n", encoding="utf-8")
    with pytest.raises(ProfileError, match="not a valid suppression file"):
        load_suppressions("acme")


def test_an_empty_suppression_file_loads_as_empty(tmp_path, monkeypatch):
    monkeypatch.setenv(PROFILE_DIR_ENV, str(tmp_path))
    suppression_path("acme").parent.mkdir(parents=True, exist_ok=True)
    suppression_path("acme").write_text("", encoding="utf-8")
    assert load_suppressions("acme").suppressions == []


