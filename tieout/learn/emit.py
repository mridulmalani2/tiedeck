"""Writing the profile YAML, with provenance on every derived value.

The profile is the artefact that makes the tool trustworthy rather than
arbitrary. A user who is told "the logo should be at 852pt" has no reason to
believe it; a user who reads

    content: {left: 852, top: 24, width: 72, height: 24, tolerance_pt: 2.0}
    # logo geometry on 12 content slides, invariant with an observed spread of
    # 0.0pt giving a tolerance of 2pt

can check the claim against their own deck. So section 16's rule is absolute: if
the provenance comment cannot be written, the value is not emitted.

``ruamel.yaml`` in round-trip mode, so a user's own edits and comments survive
re-learning.

Provenance is written twice, deliberately: as ``why:`` comments above each value,
which is the document section 8.5 specifies and what a person actually reads, and
as a generated ``provenance`` block at the end of the file, which is what the
rules read to populate a finding's ``expected_provenance``.

The single-copy design -- comments only, recovered by the loader -- was built
first and abandoned. YAML attaches a leading comment to the *preceding* sibling
key, so recovery silently mis-assigned notes across section boundaries: a finding
about the grid cited the margin derivation. A finding that cites the wrong
evidence is worse than one that cites none, because the whole purpose of
provenance is to let the reader check the claim.
"""

from __future__ import annotations

import io
from collections.abc import Iterator
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Final

from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap, CommentedSeq
from ruamel.yaml.scalarstring import DoubleQuotedScalarString

from tieout.profile.schema import Profile

#: Column the value-explaining comments are wrapped at.
_COMMENT_WIDTH: Final[int] = 84

#: Column the emitter folds scalars at. Named because :func:`_safe_key` has to
#: know it: a plain key folded at this column would not load back.
_WIDTH: Final[int] = 100

#: Prefix marking a question the interview deferred. Section 8.4 requires these
#: to appear above the field they concern so the user can find them.
QUESTION_PREFIX: Final[str] = "QUESTION:"

#: Prefix marking the provenance of a derived value, used by the loader to read
#: it back.
PROVENANCE_PREFIX: Final[str] = "why:"


def _yaml() -> YAML:
    handler = YAML()
    handler.default_flow_style = False
    handler.width = _WIDTH
    handler.indent(mapping=2, sequence=4, offset=2)
    handler.preserve_quotes = True
    return handler


@dataclass(frozen=True, slots=True)
class EmitResult:
    text: str
    path: Path | None = None


def render(profile: Profile, *, questions_deferred: int = 0) -> str:
    """Render a profile to YAML with a header and per-value provenance."""
    data = _commented(profile.model_dump(mode="json", exclude_none=True))
    assert isinstance(data, CommentedMap)

    annotate_indents(data)
    _attach_provenance(data, profile)
    _attach_questions(data, profile)
    _attach_section_notes(data, profile)

    stream = io.StringIO()
    stream.write(_header(profile, questions_deferred=questions_deferred))
    _yaml().dump(data, stream)
    return stream.getvalue()


def write(profile: Profile, path: str | Path, *, questions_deferred: int = 0) -> EmitResult:
    """Write a profile, creating the directory if needed."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    text = render(profile, questions_deferred=questions_deferred)
    target.write_text(text, encoding="utf-8")
    return EmitResult(text=text, path=target)


def _header(profile: Profile, *, questions_deferred: int) -> str:
    generated = profile.generated_at or datetime.now(UTC).strftime("%Y-%m-%d")
    lines = [f"# Generated by tieout learn on {generated} from:"]
    for source in profile.sources or ["(no source recorded)"]:
        lines.append(f"#   - {source}")

    answered = len([q for q in profile.questions if q.answered])
    total = len(profile.questions)
    if total:
        lines.append(
            f"# Answered {answered} of {total} questions."
            + (
                f" {questions_deferred or total - answered} deferred, see "
                f"{QUESTION_PREFIX} comments below."
                if total - answered
                else ""
            )
        )
    else:
        lines.append("# No questions: every rule was settled from the evidence.")
    lines.append(
        "#"
    )
    lines.append(
        "# Comments marked 'why:' record the evidence behind the value above them."
    )
    lines.append(
        "# They are regenerated by `tieout learn`; your own comments and edits are"
    )
    lines.append(
        "# preserved. Add a field path to `locks` to protect an edit from re-learning."
    )
    return "\n".join(lines) + "\n"


